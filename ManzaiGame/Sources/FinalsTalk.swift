            if compat { return "呼吸だけで会話しとったな。ええコンビになった。" }
            if tired { return "後半、足腰が売り切れとった。舞台は四分でも、体は一年もんや。" }
        case "花園 千代":
            if revival { return "昼からもう一本、体も心もようもったなぁ。その根性ごと点数に入れたいくらいや。" }
            if compat { return "息の合い方が発明やわ。どっちかが半歩引く瞬間、全部同じ拍やった。" }
            if nervous { return "緊張してたなぁ。ええねん、緊張は真剣の証や。ただ、相方の顔だけは見たりや。" }
        case "卯月 走太":
            if hana { return "理屈を全部すっ飛ばして客を持っていく瞬間があって、ああいうのだけは計算できないんですよ。ずるい。" }
        case "白波 剛":
            if revival { return "昼に一回死んで、夜に生き返った奴の声だった。ああいう声は、狙って出ねえんだよ。" }
            if nervous { return "声が震えてたな。でもよ、震えたまま最後までやり切った。それは弱さじゃねえ、強さだ。" }
        case "目白 慧":
            if compat { return "台本に書けない部分——受けの表情、間の詰め方——が全て加点でした。あれはコンビの資産です。" }
        case "神楽坂 とんぼ":
            if nervous { return "震えてましたな。けどね、震えを『間』に化かした瞬間が一回あった。あれができりゃ、あとは場数です。" }
