enum FinalsJudgeTalk {
    /// 決勝の表示点 → 帯（決勝は全組が高水準なので、表示点の上の方で刻む・表示演出【仮】）
    static func band(_ score: Int) -> Character {
        switch score {
        case 95...: return "A"
        case 91...94: return "B"
        case 87...90: return "C"
        default: return "D"
        }
    }

    /// 講評1本。条件フックが当たればそれを優先し、無ければ帯の文から決定的に選ぶ。
    /// high=最高点の審査員（褒めるフック＝相性・華・敗者復活だけ）／false=最低点の審査員（気づかい・指摘のフック＝メンタル・体力だけ）。
    /// 司会の振り（「◯点。いかがでしたか？」／「少し辛めでした」）と講評の向きを食い違わせない
    static func comment(judge: String, score: Int, state s: GameState, viaRevival: Bool, high: Bool, salt: Int) -> String {
        if let hook = hook(judge: judge, state: s, viaRevival: viaRevival, high: high) { return hook }
        let pool = (lines[judge]?[band(score)] ?? []).filter { !$0.contains("笑") && !(high && lowOnly.contains($0)) }
        guard !pool.isEmpty else { return "……以上です。" }
        return pool[((salt % pool.count) + pool.count) % pool.count]
    }

    private static func hook(judge: String, state s: GameState, viaRevival: Bool, high: Bool) -> String? {
        // 褒めるフックは最高点の人だけ、気づかい・指摘のフックは最低点の人だけ
        let compat = high && s.compat >= 18
        let hana = high && s.華 >= 90
        let revival = high && viaRevival
        let nervous = !high && s.メンタル < 40
        let tired = !high && s.stamina < 30
        switch judge {
        case "天堂寺 銀郎":
            if compat { return "呼吸だけで会話しとったな。ええコンビになった。" }
            if tired { return "後半、足腰が売り切れとった。舞台は四分でも、体は一年もんや。" }
        case "花園 千代":
            if revival { return "昼からもう一本、体も心もようもったなぁ。その根性ごと点数に入れたいくらいや。" }
            if compat { return "息の合い方が発明やわ。どっちかが半歩引く瞬間、全部同じ拍やった。" }
            if nervous { return "緊張してたなぁ。ええねん、緊張は真剣の証や。ただ、相方の顔だけは見たりや。" }
        case "卯月 走太":
            if hana { return "理屈を全部すっ飛ばして客を持っていく瞬間があって、ああいうのだけは計算できないんですよ。ずるい。" }
        case "白波 剛":
            if revival { return "昼に一回死んで、夜に生き返った奴の声だった。ああいう声は、狙って出ねえんだよ。" }
            if nervous { return "声が震えてたな。でもよ、震えたまま最後までやり切った。それは弱さじゃねえ、強さだ。" }
        case "目白 慧":
            if compat { return "台本に書けない部分——受けの表情、間の詰め方——が全て加点でした。あれはコンビの資産です。" }
        case "神楽坂 とんぼ":
            if nervous { return "震えてましたな。けどね、震えを『間』に化かした瞬間が一回あった。あれができりゃ、あとは場数です。" }
            if tired { return "後半、噺で言う『息切れの間延び』が出ました。芸より先に、寝なさい。" }
        case "音羽 ルリ":
            if revival { return "昼のあの空気からここまで戻してくるの、メンタルお化けすぎる。" }
            if hana { return "センターマイクの前に立った瞬間の『圧』ね。あれは稽古じゃ作れない。持って生まれて、磨いた人だけのやつ。" }
        default: break
        }
        return nil
    }

