import Foundation

enum FanReportData {
    /// 架空SNSの名前【仮】（fan_report_design §4）
    static let sns = "ヒトコエ"

    /// A帯×ハマった夜（§2 #8・#9・#11・#128・#129・#131・#132）。〈名〉にコンビ名が入る。
    /// 「何回も見てるネタ」前提の #10・#130 は結成1年目と噛み合わないので外した。
    private static let burstLines = [
        "今日の〈名〉、何かが起きてた。いつも面白いけど今日のは違う。神回。",
        "〈名〉、客席と完全に噛み合ってた。ああいう日ってあるんだな。",
