        "〈名〉、序盤の一言で空気が変わった瞬間、鳥肌立った。ああいう日に立ち会えるのが幸せ。",
        "〈名〉、途中から観客の声が波みたいに重なってた。あれは仕込めない、起きるものだ。",
        "いつも通りのはずが、今日の〈名〉だけ空気の密度が違った。当たり日を引いた組は強い。",
        "〈名〉、出てきた瞬間から客席の期待が違った。終わったあと拍手が鳴りやまなかった。",
        "〈名〉のあの夜は忘れない。隣の知らない人と顔を見合わせた。",
        "〈名〉、後ろの立ち見までずっと揺れてた。見に来てよかった。",
        "〈名〉目当てじゃなかったのに、帰り道ずっと〈名〉の話をしてた。",
        "今日の〈名〉、途中で拍手が起きてた。予選であれは初めて見た。",
        "〈名〉、今日は一回もウケが途切れなかった。あっという間だった。",
        "友だちに連れてこられただけなのに、〈名〉に全部持っていかれた。",
        "〈名〉の当たり日に居合わせた人、おめでとう。たぶん今年いちばんの夜。",
        "〈名〉、礼をしたとき客席から声が飛んでた。ああいう空気は久々。",
        "〈名〉、いつも通ってる劇場の空気と別物だった。何回でも思い出せる。",
    ]

    /// ハマった夜の一言。選び方は salt 剰余＝乱数非消費（紙講評と同じ）
    static func burst(name: String, salt: Int) -> String {
        let n = burstLines.count
        return burstLines[((salt % n) + n) % n].replacingOccurrences(of: "〈名〉", with: name)
    }
}
