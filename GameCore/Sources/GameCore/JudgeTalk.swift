    /// salt と差し込み口の番号から決定的に散らす（SplitMix 風の混ぜ）。RandomSource は使わない。
    static func mix(_ salt: Int, _ k: Int) -> Int {
        var z = UInt64(bitPattern: Int64(salt)) &+ UInt64(k) &* 0x9E3779B97F4A7C15
        z = (z ^ (z >> 30)) &* 0xBF58476D1CE4E5B9
        z = (z ^ (z >> 27)) &* 0x94D049BB133111EB
        z ^= z >> 31
        return Int(z % UInt64(Int.max))
    }

    /// テンプレートの差し込み口を埋める。{題} はネタ名が無ければ「このネタ」に落とす（候補選びで外すので通常は来ない）。
    static func fill(_ template: String, scene: Scene, salt: Int) -> String {
        let table = vocab[scene.kata] ?? vocab[nil]!
        var s = template
        for (i, slot) in Slot.allCases.enumerated() {
            let token = "{\(slot.rawValue)}"
            guard s.contains(token), let list = table[slot], !list.isEmpty else { continue }
            s = s.replacingOccurrences(of: token, with: list[mix(salt, i + 1) % list.count])
        }
        s = s.replacingOccurrences(of: "{題}", with: scene.netaName.map { "『\($0)』" } ?? "このネタ")
        return s
    }

    /// 候補から1本（ネタ名が無い時は {題} 行を外す）。外して空なら元の候補のまま（fill が「このネタ」に落とす）。
    static func pick(_ pool: [String], scene: Scene, salt: Int, k: Int) -> String? {
        let usable = scene.netaName == nil ? pool.filter { !$0.contains("{題}") } : pool
        let list = usable.isEmpty ? pool : usable
        guard !list.isEmpty else { return nil }
        return list[mix(salt, k) % list.count]
    }

    // MARK: 決勝

    /// 決勝の表示点 → 帯（決勝は全組が高水準なので、表示点の上の方で刻む・表示演出【仮】）
    public static func band(_ score: Int) -> Character {
        switch score {
        case 95...: return "A"
        case 91...94: return "B"
        case 87...90: return "C"
        default: return "D"
        }
    }

    /// 司会が審査員のボケ行を拾う1拍（mc＝司会の返し／reply＝審査員の言い直し・差し込み済み）
    public struct Pickup: Equatable {
        public let mc: String
        public let reply: String?
    }

    public struct FinalComment: Equatable {
        public let text: String
        public let pickup: Pickup?
    }

    /// 決勝の講評1本。high=最高点の審査員（褒めのフック・褒めの場面だけ）／false=最低点の審査員（気づかい・惜しさだけ）。
    /// 優先: 状態フック → （場面の行＋帯の行）を salt で。
    public static func finalComment(judge: String, score: Int, high: Bool, scene: Scene, salt: Int) -> FinalComment {
        let template: String
        if let hooks = hookLines(judge: judge, scene: scene, high: high), let h = pick(hooks, scene: scene, salt: salt, k: 11) {
            template = h
        } else {
            var pool = (bandLines[judge]?[band(score)] ?? []).filter { high ? !isLowOnly($0) : true }
            pool += sceneLines(judge: judge, scene: scene, high: high)
            template = pick(pool, scene: scene, salt: salt, k: 13) ?? "{締め}。以上です。"
        }
        let text = fill(template, scene: scene, salt: salt)
        return FinalComment(text: text, pickup: pickup(after: text, scene: scene, salt: salt))
    }

    /// 審査員のボケ行の後に司会が拾う1拍（無ければ nil）。行の頭で照合する。
    public static func pickup(after text: String, scene: Scene = Scene(), salt: Int = 0) -> Pickup? {
        guard let p = pickups.first(where: { text.hasPrefix($0.head) }) else { return nil }
        return Pickup(mc: p.mc, reply: p.reply.map { fill($0, scene: scene, salt: salt &+ 1) })
    }

