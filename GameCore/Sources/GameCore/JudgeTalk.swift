    static func isLowOnly(_ t: String) -> Bool { t.hasPrefix("点は辛うつけたけど") }

    /// 状態フック（最大1つ）。褒めは最高点の人だけ、気づかい・指摘は最低点の人だけ。
    static func hookLines(judge: String, scene s: Scene, high: Bool) -> [String]? {
        let compat = high && s.compat >= 18
        let hana = high && s.hana >= 90
        let revival = high && s.viaRevival
        let nervous = !high && s.mental < 40
        let tired = !high && s.stamina < 30
        switch judge {
        case "天堂寺 銀郎":
            if compat { return ["{一言}、相方の顔も見んと出とった。呼吸だけで会話しとる。", "{中}、どっちが先に動いたか分からん。ええコンビになった。"] }
            if tired { return ["{締め}の手前で、足腰が売り切れとった。舞台は四分でも、体は一年もんや。"] }
        case "花園 千代":
            if revival { return ["昼からもう一本、{題}をようもたせたなぁ。{入り}で、昼の顔からちゃんと着替えてたで。", "昼からもう一本、体も心もようもったなぁ。{締め}まで、その根性が見えてたわ。"] }
            if compat { return ["{中}でな、どっちかが半歩引く瞬間、全部同じ拍やった。息の合い方が発明やわ。"] }
            if nervous { return ["{入り}、緊張してたなぁ。ええねん、真剣の証やから、相方の顔だけは見たりや。"] }
        case "卯月 走太":
            if hana { return ["{入り}で、理屈を全部すっ飛ばして客を持っていったんですよ。ああいうのだけは計算できない。ずるいです。"] }
            if tired { return ["{中}までは完璧なんですよ。そこから先、ボケの入りが毎回半拍遅れた。体力も構成の一部なんです。"] }
        case "白波 剛":
            if revival { return ["昼に一回死んで、夜に生き返った奴の声だった！ {一言}、あれは狙って出る声じゃねえ！"] }
            if nervous { return ["{入り}、声が震えてたな。でもよ、震えたまま{締め}までやり切った、それは強さだ！"] }
        case "目白 慧":
            if compat { return ["{中}の受けの表情と間の詰め方は、台本に書けません。全て加点でした。あれはコンビの資産です。"] }
            if tired { return ["{中}から先、ボケの入りが半拍ずつ遅れました。体力も四分の設計の一部です。"] }
        case "神楽坂 とんぼ":
            if nervous { return ["{入り}、震えてましたな。けどね、{中}で震えを間に化かした瞬間が一回あった、あれができりゃあとは場数です。"] }
            if tired { return ["{締め}の手前で、噺で言う息切れの間延びが出ました。芸より先に、寝なさい。"] }
        case "音羽 ルリ":
            if revival { return ["昼のあの空気から、{入り}一発でここまで戻してくるの、メンタルお化けすぎる。"] }
            if hana { return ["センターマイクの前に立った瞬間の圧ね。{入り}で、もう客席が決まってた。"] }
            if nervous { return ["{入り}、二人とも床見てたよね。客席の誰か一人でいいから、顔見て言ってあげて。"] }
        default: break
        }
        return nil
    }

    /// その本番の事情（出順・ハマった夜・ネタの来歴）で足す行。high=褒め／low=惜しさ。審査員の軸に合う場面だけ持つ。
    static func sceneLines(judge: String, scene s: Scene, high: Bool) -> [String] {
        var out: [String] = []
        let top = s.order == 1
        let last = s.order != nil && s.order == s.lastOrder
        func add(_ cond: Bool, _ hi: String, _ lo: String) { if cond { out.append(high ? hi : lo) } }
        switch judge {
        case "天堂寺 銀郎":
            add(s.isRevivalNeta, "{題}、何年か寝かせたな。寝かせた分だけ{一言}が太うなっとる。",
                "{題}は古い型のまま出しよった。{入り}だけでも今の間に直せ。")
            add(s.isTeppan, "{題}、かけ込んだネタや。{締め}に迷いがない。",
                "かけ込んだネタは楽をする。{中}で手が抜けとった。")
            add(last, "大トリで{締め}まで崩さんかった。ええ終いや。",
                "大トリやのに{入り}が軽い。最後の組は重う入れ。")
        case "花園 千代":
            add(s.isRevivalNeta, "{題}、昔よりずっとあんたらの顔になってるわぁ。古いネタが育つて、ほんまにあるんやね。",
                "{題}、懐かしかったけど、言い方が昔のままやったなぁ。{中}だけでも今の二人で言い直してみなはれ。")
            add(s.isFresh, "おろしたての{題}で、ようここまで来たなぁ。{一言}、もう二人の言葉になってたで。",
                "{題}、まだ二人の口に馴染んでへんねん。{中}で台本を思い出してる顔してたわ。")
            add(last, "大トリの最後に、{締め}でええ顔見せてもろたわ。待った甲斐あったで。",
                "大トリはな、客も疲れてるんよ。{入り}で一回、客の手ぇ握ったらなあかん。")
        case "卯月 走太":
