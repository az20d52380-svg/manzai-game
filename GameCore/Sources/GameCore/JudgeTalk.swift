            self.isFresh = isFresh; self.burst = burst; self.margin = margin; self.order = order; self.lastOrder = lastOrder
            self.viaRevival = viaRevival; self.compat = compat; self.stamina = stamina; self.mental = mental; self.hana = hana
        }

        /// ゲームの状態から組み立てる（純関数）。neta=nil（ネタ未選択）でも崩れない。
        public static func from(state s: GameState, neta: Neta?, config: GameConfig, year: Int,
                                burst: Bool = false, margin: Double? = nil, order: Int? = nil, viaRevival: Bool = false) -> Scene {
            let name = neta?.name.trimmingCharacters(in: .whitespacesAndNewlines)
            return Scene(netaName: (name?.isEmpty ?? true) ? nil : name,
                         kata: neta?.kata,
                         isTeppan: neta?.isTeppan(config: config) ?? false,
                         isRevivalNeta: neta?.isRevival(currentYear: year, config: config) ?? false,
                         isFresh: neta.map { $0.stageCount <= 2 } ?? false,
                         burst: burst, margin: margin, order: order, viaRevival: viaRevival,
                         compat: s.compat, stamina: s.stamina, mental: s.メンタル, hana: s.華)
        }
    }

